"""Annual GST reconciliation dashboard (Excel, all clients) and client compliance summary (PDF)."""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, NamedStyle, PatternFill
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

from .. import PRODUCT_FULL_NAME, TAGLINE
from ..compliance.summary import RAG_LABEL, ClientCompliance
from ..core.money import fmt_inr
from .excel_report import _register_styles, _Sheet, _write_table, section_label
from .pdf_report import NAVY, TEAL, _table

RAG_FILL = {"red": "FFCDD2", "amber": "FFF3C4", "green": "C8E6C9", "grey": "ECEFF1"}
DISCLAIMER = ("Status is derived from the data imported into FIN TAX PRO. The software has no access to the GST "
              "portal: 'GSTR-3B imported' does not confirm filing. Due dates follow the client's return frequency "
              "(monthly or QRMP) and include only the CBIC extensions recorded in the application.")


def _rag_styles(wb) -> None:
    for k, color in RAG_FILL.items():
        wb.add_named_style(NamedStyle(f"ftp_rag_{k}", fill=PatternFill("solid", fgColor=color), font=Font(bold=True)))


def _rag_col(col: int):
    labels = {v: k for k, v in RAG_LABEL.items()}

    def style(_r, c, v):
        return f"ftp_rag_{labels[v]}" if c == col and v in labels else None
    return style


def build_compliance_workbook(summaries: list[ClientCompliance], fy: str) -> Workbook:
    wb = Workbook(write_only=True)
    _register_styles(wb)
    _rag_styles(wb)
    sh = _Sheet(wb, "Annual Dashboard", [34, 18, 16, 9, 9, 9, 15, 15, 15, 15, 10, 8])
    sh.banner(f"Annual GST reconciliation dashboard – FY {fy}", f"{TAGLINE} · prepared {datetime.now():%d-%m-%Y %H:%M}",
              12)
    rows = [[c.name, c.gstin, RAG_LABEL[c.rag], c.months_with_data, c.months_reconciled, c.pending,
             c.total("itc_at_risk"), c.total("itc_excess"), c.total("short_payment"),
             sum(m.itc_3b or 0 for m in c.months), c.followups_due, c.red_issues] for c in summaries]
    _write_table(sh, ["Client", "GSTIN", "Status", "Months with data", "Months clear", "Pending", "ITC at risk",
                      "3B ITC above 2B", "Possible short payment", "ITC claimed (3B 4A)", "Follow-ups due",
                      "Red issues"], rows,
                 ["text", "text", "text", "count", "count", "count", "money", "money", "money", "money", "count",
                  "count"], name="AnnualDashboard", cell_styles=_rag_col(2))
    sh.append([])
    sh.append([sh.cell(DISCLAIMER, "ftp_note")])

    ms = _Sheet(wb, "Month Status", [30, 9, 15, 30, 8, 8, 8, 8, 8, 14, 14, 14, 14, 14, 9, 70])
    ms.banner("Client-wise month status", "Documents imported, reconciliation runs and return comparison by month", 16)
    rows = []
    for c in summaries:
        for m in c.months:
            rows.append([c.name, m.period, RAG_LABEL[m.rag], "; ".join(
                f"{x.return_type} {x.due:%d-%m-%Y}{' (extended)' if x.extended else ''}" for x in m.due),
                m.purchase_docs, m.gstr2b_docs, m.sales_docs,
                         m.gstr1_docs, "Yes" if m.gstr3b_imported else "No", m.itc_2b if m.inward else None, m.itc_3b,
                         m.output_gstr1, m.output_3b, m.output_sales, m.pending,
                         " | ".join(t for _r, t in m.issues)])
    _write_table(ms, ["Client", "Period", "Status", "Returns due", "Purchase docs", "2B docs", "Sales docs", "GSTR-1 docs",
                      "3B imported", "ITC as per 2B", "ITC in 3B 4A", "Output tax GSTR-1", "Output tax 3B",
                      "Output tax sales register", "Pending", "Issues"], rows,
                 ["text", "text", "text", "wrap", "count", "count", "count", "count", "text", "money", "money",
                  "money", "money", "money", "count", "wrap"], name="MonthStatus", totals=False, cell_styles=_rag_col(2))

    iss = _Sheet(wb, "Issues", [30, 9, 14, 90])
    iss.banner("Issues to resolve", "Red items first", 4)
    rows = sorted(([c.name, m.period, r.upper(), t] for c in summaries for m in c.months for r, t in m.issues),
                  key=lambda x: (x[2] != "RED", x[0], x[1]))
    _write_table(iss, ["Client", "Period", "Severity", "Issue"], rows, ["text", "text", "text", "wrap"],
                 name="Issues", totals=False)
    iss.append([section_label(iss, "Generated by " + PRODUCT_FULL_NAME)])
    return wb


def export_compliance_excel(summaries: list[ClientCompliance], fy: str, out_path: str | Path) -> Path:
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    wb = build_compliance_workbook(summaries, fy)
    tmp = out_path.with_suffix(".tmp.xlsx")
    wb.save(tmp)
    tmp.replace(out_path)
    return out_path


def export_client_pdf(c: ClientCompliance, out_path: str | Path) -> Path:
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], textColor=NAVY, fontSize=17, alignment=0)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=TEAL)
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8, textColor=colors.HexColor("#455A64"))
    cell = ParagraphStyle("cell", parent=styles["Normal"], fontSize=7.5, leading=9)
    story = [Paragraph("GST compliance summary", h1), Paragraph(TAGLINE, small), Spacer(1, 3 * mm),
             Paragraph(f"<b>{c.name}</b> &nbsp; GSTIN {c.gstin} &nbsp; FY {c.fy} &nbsp; Overall status: "
                       f"<b>{RAG_LABEL[c.rag]}</b>", styles["Normal"]), Spacer(1, 3 * mm),
             Paragraph("Key figures", h2)]
    kf = [["Measure", "Value"], ["Months with data", str(c.months_with_data)],
          ["Months reconciled with nothing pending", str(c.months_reconciled)],
          ["Exceptions pending review", str(c.pending)], ["ITC at risk", "Rs. " + fmt_inr(c.total("itc_at_risk"))],
          ["ITC in GSTR-3B above GSTR-2B", "Rs. " + fmt_inr(c.total("itc_excess"))],
          ["Possible short payment of output tax", "Rs. " + fmt_inr(c.total("short_payment"))],
          ["Supplier follow-ups due", str(c.followups_due)]]
    story += [_table(kf, [100 * mm, 50 * mm], money_cols=(1,)), Spacer(1, 3 * mm), Paragraph("Month status", h2)]
    data = [["Period", "Status", "Returns due", "3B imported", "ITC 2B", "ITC 3B", "Output GSTR-1",
             "Output 3B", "Pending", "Issues"]]
    rag_rows = []
    for i, m in enumerate(c.months, start=1):
        due = "<br/>".join(f"{x.return_type}{' (optional)' if x.optional else ''} {x.due:%d-%m-%Y}"
                           f"{' *' if x.extended else ''}" for x in m.due)
        data.append([m.period, RAG_LABEL[m.rag], Paragraph(due, cell),
                     "Yes" if m.gstr3b_imported else "No", fmt_inr(m.itc_2b) if m.inward else "",
                     fmt_inr(m.itc_3b) if m.itc_3b is not None else "",
                     fmt_inr(m.output_gstr1) if m.output_gstr1 is not None else "",
                     fmt_inr(m.output_3b) if m.output_3b is not None else "", str(m.pending),
                     Paragraph("<br/>".join(t for _r, t in m.issues).replace("₹", "Rs. "), cell)])
        rag_rows.append((i, m.rag))
    t = _table(data, [15 * mm, 24 * mm, 38 * mm, 15 * mm, 22 * mm, 22 * mm, 22 * mm, 22 * mm, 13 * mm,
                      64 * mm], money_cols=(4, 5, 6, 7))
    for i, rag in rag_rows:
        t.setStyle([("BACKGROUND", (1, i), (1, i), colors.HexColor("#" + RAG_FILL[rag]))])
    story += [t, Spacer(1, 2 * mm), Paragraph("* extended date recorded from a CBIC notification", small),
              Spacer(1, 2 * mm), Paragraph(DISCLAIMER + f" Generated by {PRODUCT_FULL_NAME}.", small)]
    doc = SimpleDocTemplate(str(out_path), pagesize=landscape(A4), leftMargin=10 * mm, rightMargin=10 * mm,
                            topMargin=10 * mm, bottomMargin=10 * mm, title="GST compliance summary",
                            author="FIN TAX PRO")
    doc.build(story)
    return out_path
