"""One-page-per-section PDF summary for the client file (reportlab)."""
from __future__ import annotations

from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .. import PRODUCT_FULL_NAME, TAGLINE
from ..core.models import relabel
from ..core.money import fmt_inr
from ..engine.summary import DASHBOARD_LABELS, category_summary, dashboard, supplier_summary

NAVY = colors.HexColor("#1F3864")
TEAL = colors.HexColor("#00897B")


def _table(data, widths, money_cols=()):
    t = Table(data, colWidths=widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#B0BEC5")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F1F8F7")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]
    for c in money_cols:
        style.append(("ALIGN", (c, 1), (c, -1), "RIGHT"))
    t.setStyle(TableStyle(style))
    return t


def export_pdf(ctx, out_path: str | Path) -> Path:
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines, client, run = ctx.result.lines, ctx.client, ctx.run
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], textColor=NAVY, fontSize=18, alignment=0)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=TEAL)
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8, textColor=colors.HexColor("#455A64"))
    dash = dashboard(lines)
    lab = lambda t: relabel(t, run.comparison)  # noqa: E731
    story = [
        Paragraph("FIN TAX PRO – GST Reconciliation Summary", h1),
        Paragraph(TAGLINE, small), Spacer(1, 4 * mm),
        Paragraph(f"<b>{client.name}</b> &nbsp; GSTIN {client.gstin} &nbsp; FY {run.financial_year} &nbsp; "
                  f"Period {run.period_from} to {run.period_to} &nbsp; Run #{run.id}", styles["Normal"]),
        Spacer(1, 4 * mm), Paragraph("Key figures", h2),
    ]
    data = [["Metric", "Value"]]
    for key, label, kind in DASHBOARD_LABELS:
        v = dash[key]
        data.append([lab(label), "Rs. " + fmt_inr(v) if kind == "money" else str(v)])
    data.append(["Matching percentage", f"{dash['match_percentage']}%"])
    story.append(_table(data, [110 * mm, 50 * mm], money_cols=(1,)))
    story += [Spacer(1, 4 * mm), Paragraph("Category summary", h2)]
    data = [[lab(h) for h in ("Category", "Lines", "Books ITC", "GSTR-2B ITC", "Difference", "ITC at risk")]]
    for r in category_summary(lines):
        if r.lines:
            data.append([lab(r.category.value), r.lines, fmt_inr(r.books.itc), fmt_inr(r.gstr2b.itc),
                         fmt_inr(r.itc_difference), fmt_inr(r.itc_at_risk)])
    story.append(_table(data, [85 * mm, 15 * mm, 30 * mm, 30 * mm, 30 * mm, 30 * mm], money_cols=(2, 3, 4, 5)))
    story += [PageBreak(), Paragraph(lab("Top suppliers by ITC difference"), h2)]
    data = [[lab(h) for h in ("GSTIN", "Supplier", "Books ITC", "GSTR-2B ITC", "Difference", "Missing GSTR-2B",
                              "Missing Books", "Unresolved")]]
    for r in supplier_summary(lines)[:25]:
        data.append([r.gstin, r.name[:38], fmt_inr(r.books.itc), fmt_inr(r.gstr2b.itc), fmt_inr(r.itc_difference),
                     r.missing_in_2b, r.missing_in_books, r.unresolved])
    story.append(_table(data, [36 * mm, 70 * mm, 28 * mm, 28 * mm, 28 * mm, 20 * mm, 22 * mm, 20 * mm],
                        money_cols=(2, 3, 4)))
    story += [Spacer(1, 6 * mm), Paragraph(
        lab("ITC at risk is an indicator for professional review and not a conclusion on eligibility under the CGST Act. "
        f"Generated by {PRODUCT_FULL_NAME}; full detail is in the accompanying Excel workbook."), small)]
    doc = SimpleDocTemplate(str(out_path), pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm,
                            topMargin=12 * mm, bottomMargin=12 * mm, title="GST Reconciliation Summary",
                            author="FIN TAX PRO")
    doc.build(story)
    return out_path
